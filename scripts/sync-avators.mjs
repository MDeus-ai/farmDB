import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const sourceDir = path.join(repoRoot, 'assets', 'avators');
const mobileAssetsDir = path.join(repoRoot, 'apps', 'mobile', 'assets', 'avators');
const generatedTsPath = path.join(
  repoRoot,
  'apps',
  'mobile',
  'src',
  'assets',
  'avators.generated.ts'
);

const SUPPORTED_EXTS = new Set(['.png', '.jpg', '.jpeg', '.webp']);

function formatAvatarSlugFromFilename(filename) {
  const stem = filename.replace(/\.[^.]+$/, '');
  const normalized = stem
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
  return `avator_${normalized || 'custom'}`;
}

function formatAvatarLabel(avatarKey) {
  const raw = avatarKey.replace(/^avator_/, '');
  return raw
    .split('_')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
}

function toSafeIdentifier(index, slug) {
  const clean = slug.replace(/[^a-zA-Z0-9_]/g, '_');
  return `avatorImg${index}_${clean}`;
}

if (!fs.existsSync(sourceDir)) {
  fs.mkdirSync(sourceDir, { recursive: true });
}
fs.mkdirSync(mobileAssetsDir, { recursive: true });
fs.mkdirSync(path.dirname(generatedTsPath), { recursive: true });

const files = fs
  .readdirSync(sourceDir, { withFileTypes: true })
  .filter(
    (entry) =>
      entry.isFile() && SUPPORTED_EXTS.has(path.extname(entry.name).toLowerCase())
  )
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b, 'en'));

const sourceFileSet = new Set(files);
for (const existing of fs.readdirSync(mobileAssetsDir, { withFileTypes: true })) {
  if (existing.isFile() && !sourceFileSet.has(existing.name)) {
    fs.unlinkSync(path.join(mobileAssetsDir, existing.name));
  }
}

for (const file of files) {
  fs.copyFileSync(path.join(sourceDir, file), path.join(mobileAssetsDir, file));
}

const usedSlugs = new Set();
const entries = files.map((file, idx) => {
  let key = formatAvatarSlugFromFilename(file);
  if (usedSlugs.has(key)) {
    key = `${key}_${idx + 1}`;
  }
  usedSlugs.add(key);
  const label = formatAvatarLabel(key);
  const ident = toSafeIdentifier(idx, key);
  return { file, key, label, ident };
});

const importLines = entries.map(
  (entry) => `import ${entry.ident} from '../../assets/avators/${entry.file}';`
);

const arrayLines = entries.map(
  (entry) =>
    `  { key: '${entry.key}', label: ${JSON.stringify(entry.label)}, source: ${entry.ident} },`
);

const output = [
  '// Auto-generated by scripts/sync-avators.mjs — do not edit manually.',
  ...importLines,
  '',
  'export interface MobileFolderAvatarItem {',
  '  readonly key: string;',
  '  readonly label: string;',
  '  readonly source: number;',
  '}',
  '',
  'export const MOBILE_FOLDER_AVATARS: readonly MobileFolderAvatarItem[] = [',
  ...arrayLines,
  '];',
  '',
].join('\n');

fs.writeFileSync(generatedTsPath, output, 'utf8');
console.log(
  `Synced ${entries.length} avator file(s) from assets/avators to apps/mobile/assets/avators and updated avators.generated.ts.`
);
