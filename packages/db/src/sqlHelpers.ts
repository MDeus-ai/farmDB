/**
 * Converts SQLite `?` positional placeholders to `$1, $2, ...` expected by
 * `@tauri-apps/plugin-sql` (which wraps `sqlx`), skipping quoted strings and identifiers.
 */
export function convertQuestionPlaceholdersToDollar(sql: string): string {
  let out = '';
  let paramIndex = 0;
  let inSingleQuote = false;
  let inDoubleQuote = false;

  for (let i = 0; i < sql.length; i += 1) {
    const ch = sql[i] ?? '';
    const next = sql[i + 1] ?? '';

    if (ch === "'" && !inDoubleQuote) {
      out += ch;
      if (inSingleQuote && next === "'") {
        out += next;
        i += 1;
      } else {
        inSingleQuote = !inSingleQuote;
      }
      continue;
    }

    if (ch === '"' && !inSingleQuote) {
      out += ch;
      if (inDoubleQuote && next === '"') {
        out += next;
        i += 1;
      } else {
        inDoubleQuote = !inDoubleQuote;
      }
      continue;
    }

    if (ch === '?' && !inSingleQuote && !inDoubleQuote) {
      paramIndex += 1;
      out += `$${paramIndex}`;
      continue;
    }

    out += ch;
  }

  return out;
}

/**
 * Splits a top-level comma-separated SQL projection list outside parentheses and quotes.
 */
function splitTopLevelCommas(segment: string): string[] {
  const parts: string[] = [];
  let current = '';
  let depth = 0;
  let inSingleQuote = false;
  let inDoubleQuote = false;

  for (let i = 0; i < segment.length; i += 1) {
    const ch = segment[i] ?? '';
    const next = segment[i + 1] ?? '';

    if (ch === "'" && !inDoubleQuote) {
      current += ch;
      if (inSingleQuote && next === "'") {
        current += next;
        i += 1;
      } else {
        inSingleQuote = !inSingleQuote;
      }
      continue;
    }

    if (ch === '"' && !inSingleQuote) {
      current += ch;
      if (inDoubleQuote && next === '"') {
        current += next;
        i += 1;
      } else {
        inDoubleQuote = !inDoubleQuote;
      }
      continue;
    }

    if (!inSingleQuote && !inDoubleQuote) {
      if (ch === '(') depth += 1;
      else if (ch === ')' && depth > 0) depth -= 1;
      else if (ch === ',' && depth === 0) {
        parts.push(current.trim());
        current = '';
        continue;
      }
    }

    current += ch;
  }

  if (current.trim().length > 0) {
    parts.push(current.trim());
  }

  return parts;
}

function stripIdentifierQuotes(identifier: string): string {
  const trimmed = identifier.trim();
  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith('`') && trimmed.endsWith('`'))
  ) {
    return trimmed.slice(1, -1).replace(/""/g, '"');
  }
  return trimmed;
}

/**
 * Extracts projected column names from a simple `SELECT ... FROM` or `RETURNING ...`
 * SQL statement generated by Drizzle so row objects returned from drivers like
 * `tauri-plugin-sql` (whose JSON map key ordering may be alphabetical rather than
 * SELECT-ordered) are converted to positional arrays accurately.
 */
export function extractProjectedColumns(sql: string): string[] | null {
  const trimmed = sql.trim();

  let projectionSegment: string | null = null;

  if (/^select\b/i.test(trimmed)) {
    const match = trimmed.match(/^select\s+(?:distinct\s+)?([\s\S]+?)\s+from\b/i);
    if (match?.[1]) {
      projectionSegment = match[1];
    }
  } else {
    const returningMatch = trimmed.match(/\breturning\s+([\s\S]+?);?$/i);
    if (returningMatch?.[1]) {
      projectionSegment = returningMatch[1];
    }
  }

  if (!projectionSegment) {
    return null;
  }

  const expressions = splitTopLevelCommas(projectionSegment);
  if (expressions.length === 0) {
    return null;
  }

  const columns: string[] = [];
  for (const expr of expressions) {
    if (expr === '*' || expr.endsWith('.*')) {
      return null;
    }

    const asMatch = expr.match(/\bas\s+("[^"]+"|`[^`]+`|[a-zA-Z_][a-zA-Z0-9_]*)\s*$/i);
    if (asMatch?.[1]) {
      columns.push(stripIdentifierQuotes(asMatch[1]));
      continue;
    }

    const dottedMatch = expr.match(/(?:^|\.)("[^"]+"|`[^`]+`|[a-zA-Z_][a-zA-Z0-9_]*)$/);
    if (dottedMatch?.[1]) {
      columns.push(stripIdentifierQuotes(dottedMatch[1]));
      continue;
    }

    return null;
  }

  return columns;
}

/**
 * Converts a row object into a positional array aligned with `columns` when
 * known, falling back to `Object.values(row)` for arbitrary expressions.
 */
export function mapRowObjectToValues(
  row: Record<string, unknown>,
  columns: string[] | null
): unknown[] {
  if (!columns) {
    return Object.values(row);
  }

  for (const col of columns) {
    if (!(col in row)) {
      return Object.values(row);
    }
  }

  return columns.map((col) => row[col]);
}
